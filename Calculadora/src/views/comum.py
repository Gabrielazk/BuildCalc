def fmt_moeda(valor: float) -> str:
    sep = CONFIG_APP["separador_decimal"]
    moeda = CONFIG_APP["moeda"]
    texto = f"{valor:.2f}".replace('.', sep)
    return f"{moeda} {texto}"

